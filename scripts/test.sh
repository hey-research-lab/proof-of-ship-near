#!/bin/sh
# Everything CI runs: EIP-712 vectors against viem, unit tests, the wasm build, and the sandbox tests.
set -eu
cd "$(dirname "$0")/.."
[ -d scripts/node_modules/viem ] || npm ci --prefix scripts --no-audit --no-fund >/dev/null
node scripts/vectors.mjs >/dev/null
git diff --quiet -- contract/src/vectors.json 2>/dev/null || echo "note: contract/src/vectors.json changed (regenerated by viem)"
cargo test -p ship-escrow --locked
./scripts/build.sh
cargo test -p integration-tests --locked -- --test-threads=1
